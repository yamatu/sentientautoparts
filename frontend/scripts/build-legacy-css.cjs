// Preserve source CSS and assets, isolate it from Tailwind/admin styles.
// Run after preparing public/legacy/theme from the read-only PHP archive.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const base = path.join(__dirname, '../public/legacy/theme/css');
const files = ['bootstrap.css', 'root.css', 'base.css', 'index.css'];
const results = files.map(file => {
  const root = postcss.parse(fs.readFileSync(path.join(base, file), 'utf8'), { from: file });
  root.walkRules(rule => {
    let parent = rule.parent;
    while (parent && parent.type !== 'root') {
      if (parent.type === 'rule' || (parent.type === 'atrule' && /keyframes$/i.test(parent.name))) { rule.selector = rule.selector.replace(/&&/g, '&'); return; }
      parent = parent.parent;
    }
    rule.selectors = rule.selectors.map(selector => {
      const normalized = selector.replace(/\b(?:html|body)\b|:root/g, '.legacy-site').replace(/\.legacy-site\s+\.legacy-site/g, '.legacy-site');
      return normalized.includes('.legacy-site') ? normalized : `.legacy-site ${normalized}`;
    });
  });
  root.walkDecls(d => { d.value = d.value.replace(/url\((['"]?)\.\.\//g, 'url($1/legacy/theme/').replace(/NotoSansHans-Bold\.0tf/g, 'NotoSansHans-Bold.otf').replace(/HelveticaNeue\.ttf/g, 'HelveticaNeue.ttc'); });
  return root.toString();
});
fs.writeFileSync(path.join(__dirname, '../src/app/legacy-theme.css'), '/* Generated by scripts/build-legacy-css.cjs; do not edit. */\n' + results.join('\n'));
// Recover only resized copies of the exact missing original filename.
const uploads = path.join(__dirname, '../public/legacy/uploads');
const fallbacks = {};
function walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) { walk(file); continue; }
    const match = entry.name.match(/^thumb_(\d+)_(\d+)_(.+)$/);
    if (!match) continue;
    const original = path.join(dir, match[3]);
    if (fs.existsSync(original)) continue;
    const key = '/legacy/uploads/' + path.relative(uploads, original).split(path.sep).join('/');
    const area = Number(match[1]) * Number(match[2]);
    if (!fallbacks[key] || area > fallbacks[key].area) fallbacks[key] = { area, url: '/legacy/uploads/' + path.relative(uploads, file).split(path.sep).join('/') };
  }
}
walk(uploads);
fs.writeFileSync(path.join(__dirname, '../src/lib/legacy-image-fallbacks.json'), JSON.stringify(Object.fromEntries(Object.entries(fallbacks).map(([k, v]) => [k, v.url])), null, 2));
console.log('Generated isolated legacy-theme.css and exact media fallback map');
